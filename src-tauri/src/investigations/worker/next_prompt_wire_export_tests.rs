//! AC-0287: opt-in export of actual production DTOs from the scripted worker.
//! These fixtures establish wire compatibility, never real-provider quality.
use super::*;

#[test]
#[ignore = "writes three scripted worker wire fixtures to /tmp/cartograph-708-wire"]
fn next_prompt_export_scripted_wire_fixtures() {
    let output = std::path::Path::new("/tmp/cartograph-708-wire");
    std::fs::create_dir_all(output).unwrap();
    for scenario in ["supported", "insufficient", "terminal"] {
        let mut scripted = NextProvider::new(false);
        if scenario != "terminal" {
            scripted.source_scenario = Some(if scenario == "supported" {
                SourceScenario::Acquired
            } else {
                SourceScenario::Unavailable
            });
        }
        let provider = Arc::new(scripted);
        let fixture = NextFixture::with_source_obligation(
            provider.as_ref(),
            SpecialistId::DomainAnalystV10,
            scenario != "terminal",
        );
        if scenario == "insufficient" {
            rusqlite::Connection::open(
                fixture
                    .base
                    .base
                    .app_data
                    .join("retained-source/captures.sqlite"),
            )
            .unwrap()
            .execute("DELETE FROM objects", [])
            .unwrap();
        }
        fixture.run(provider.clone());
        let state = fixture.base.base.app.state::<AppState>();
        let jobs = state.jobs.lock().unwrap();
        // Use the same validated reads as IPC; no handwritten DTO/hash/sequence.
        let detail = jobs.investigation(&fixture.id).unwrap();
        let result = jobs.investigation_result(&fixture.id).unwrap();
        assert_eq!(detail.summary.schema_version, 7);
        assert_eq!(detail.summary.has_result, scenario != "terminal");
        assert_eq!(
            detail.summary.status,
            if scenario == "terminal" {
                InvestigationStatus::Failed
            } else {
                InvestigationStatus::Completed
            }
        );
        assert_eq!(
            provider.observed.calls.load(Ordering::SeqCst),
            if scenario == "terminal" { 2 } else { 3 }
        );
        if let Some(result) = &result {
            assert_eq!(result.schema_version, 7);
            assert!(
                result
                    .disclosure_hash
                    .as_ref()
                    .unwrap()
                    .starts_with("investigation-disclosure-v6:")
            );
            assert_eq!(
                detail.summary.completion_outcome,
                Some(if scenario == "supported" {
                    InvestigationCompletionOutcome::Supported
                } else {
                    InvestigationCompletionOutcome::InsufficientEvidence
                })
            );
        }
        let mut events = Vec::new();
        let mut after = 0;
        loop {
            let page = jobs.investigation_events(&fixture.id, after).unwrap();
            assert!(page.next_sequence > after || !page.has_more);
            events.extend(page.items);
            after = page.next_sequence;
            assert!(events.len() <= INVESTIGATION_V2_POLICY.journal_events() as usize);
            if !page.has_more {
                break;
            }
        }
        assert_eq!(after, detail.summary.last_event_sequence);
        for (index, event) in events.iter().enumerate() {
            assert_eq!(event.sequence, index as u64 + 1);
        }
        let wire = serde_json::json!({"detail":detail,"result":result,"events":events});
        std::fs::write(
            output.join(format!("completion-v10-{scenario}.json")),
            serde_json::to_vec_pretty(&wire).unwrap(),
        )
        .unwrap();
    }
    std::fs::write(output.join("README.txt"),"These JSON files are actual Rust production detail/result/event DTOs from next_prompt_export_scripted_wire_fixtures using the real mocked worker and retained temporary capture. Supported and insufficient scenarios each run three scripted model calls; terminal runs two. No live provider was called. Hashes, IDs, timestamps and journal sequences are generated by production code.\n").unwrap();
}
